"""
Project 1: Simple Cache Server
Architecture: FastAPI -> Redis -> Fake Database
Pattern: Cache-Aside (a.k.a. Lazy Loading)

HOW TO RUN THIS FILE (on your own machine, not inside the notebook):

    1. Make sure Redis is running:
         docker run -d --name redis-dev -p 6379:6379 redis:7
         (or: sudo service redis-server start   if installed natively)

    2. Install dependencies:
         pip install fastapi uvicorn redis

    3. Start the server:
         uvicorn main:app --reload

    4. Try it:
         curl http://localhost:8000/user/7        (1st call -> slow, cache miss)
         curl http://localhost:8000/user/7        (2nd call -> fast, cache hit)
         curl -X DELETE http://localhost:8000/cache/user/7   (invalidate)
         curl http://localhost:8000/cache/stats   (see hit/miss counters)

    5. Interactive API docs (auto-generated by FastAPI):
         http://localhost:8000/docs
"""

import json
import time

import redis
from fastapi import FastAPI, HTTPException

# ---------------------------------------------------------------------------
# Redis connection
# ---------------------------------------------------------------------------
r = redis.Redis(host="localhost", port=6379, decode_responses=True)

CACHE_TTL_SECONDS = 30  # how long a cached user stays valid before auto-expiring

app = FastAPI(
    title="Simple Cache Server",
    description="Phase 2 Project 1 -- FastAPI + Redis cache-aside pattern",
)


# ---------------------------------------------------------------------------
# Fake "database" -- simulates a slow query (e.g. a real Postgres join)
# ---------------------------------------------------------------------------
def fake_slow_database(user_id: int) -> dict:
    if user_id <= 0:
        raise ValueError("user_id must be positive")

    time.sleep(0.2)  # pretend this is an expensive DB round trip
    return {
        "user_id": user_id,
        "name": f"User_{user_id}",
        "email": f"user{user_id}@example.com",
    }


# ---------------------------------------------------------------------------
# Cache-aside logic, reused by every route below
# ---------------------------------------------------------------------------
def get_user_cached(user_id: int) -> dict:
    cache_key = f"user:{user_id}"

    cached = r.get(cache_key)
    if cached is not None:
        r.incr("stats:cache_hits")
        return json.loads(cached)

    r.incr("stats:cache_misses")
    data = fake_slow_database(user_id)
    r.set(cache_key, json.dumps(data), ex=CACHE_TTL_SECONDS)
    return data


# ---------------------------------------------------------------------------
# Routes
# ---------------------------------------------------------------------------
@app.get("/user/{user_id}")
def get_user(user_id: int):
    try:
        return get_user_cached(user_id)
    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))


@app.delete("/cache/user/{user_id}")
def invalidate_user_cache(user_id: int):
    deleted = r.delete(f"user:{user_id}")
    return {
        "status": "cache invalidated" if deleted else "no cache entry existed",
        "user_id": user_id,
    }


@app.get("/cache/stats")
def cache_stats():
    hits = int(r.get("stats:cache_hits") or 0)
    misses = int(r.get("stats:cache_misses") or 0)
    total = hits + misses
    hit_rate = round((hits / total) * 100, 1) if total else 0.0
    return {
        "cache_hits": hits,
        "cache_misses": misses,
        "hit_rate_percent": hit_rate,
    }


@app.get("/health")
def health():
    return {"redis_connected": r.ping()}
