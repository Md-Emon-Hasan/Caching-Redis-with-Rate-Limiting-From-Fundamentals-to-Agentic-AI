"""
============================================================================
 PHASE 5 - CONCEPT 1: LLM RESPONSE CACHE
============================================================================

WHY THIS MATTERS
----------------
Every call to an LLM (GPT-4, Claude, Llama, etc.) costs money AND time:
  - Money : you pay per input + output token.
  - Time  : a single call can take 1-10 seconds.

But in real apps, users ask the SAME (or very similar) questions again and
again. "What is your refund policy?" might be asked 5,000 times a day.

If the answer does not change, calling the LLM 5,000 times is pure waste.

THE IDEA
--------
    Question  ->  Redis  ->  (miss?)  ->  LLM  ->  store in Redis  ->  answer
    Question  ->  Redis  ->  (hit!)   ->  answer   (no LLM call at all)

This is the classic "Cache-Aside" pattern you learned in Phase 1, now
applied to an LLM instead of a database.

KEY DESIGN DECISION: THE CACHE KEY
----------------------------------
Two questions that are byte-for-byte identical should share one answer.
So we hash the *prompt* (plus the model + settings) into a short, fixed
key. We use SHA-256 so that even a very long prompt becomes a tiny key.

We include the model name and temperature in the key because:
  - Different Groq models give different answers to the same prompt.
  - temperature=0 (deterministic) is cacheable; temperature=0.9 is not
    (you WANT variety), so you might choose NOT to cache those.
============================================================================
"""

import hashlib
import json
import time

import redis  # pip install redis


# ---------------------------------------------------------------------------
# 1. CONNECT TO REDIS
# ---------------------------------------------------------------------------
# decode_responses=True  ->  Redis returns Python str instead of raw bytes,
#                            so we don't have to call .decode() everywhere.
r = redis.Redis(host="localhost", port=6379, db=0, decode_responses=True)


# ---------------------------------------------------------------------------
# 2. BUILD A DETERMINISTIC CACHE KEY FROM THE REQUEST
# ---------------------------------------------------------------------------
def make_llm_cache_key(prompt: str, model: str, temperature: float) -> str:
    """
    Turn (prompt + model + temperature) into a short, unique, stable key.

    Why hash? Because a prompt can be thousands of characters long, and
    Redis keys should be short. A hash gives us a fixed 64-char fingerprint.

    Why include model + temperature? Because the SAME prompt with a DIFFERENT
    model or temperature is effectively a different request and deserves its
    own cache entry.
    """
    # Combine everything that affects the answer into one canonical string.
    raw = json.dumps(
        {"prompt": prompt, "model": model, "temperature": temperature},
        sort_keys=True,  # sort_keys makes the string order-independent
    )
    # SHA-256 fingerprint of that string.
    digest = hashlib.sha256(raw.encode("utf-8")).hexdigest()
    # Namespacing with a prefix ("llm:") keeps this data separate from
    # sessions, rate-limiters, etc. living in the same Redis instance.
    return f"llm:response:{digest}"


# ---------------------------------------------------------------------------
# 3. THE (FAKE) LLM CALL
# ---------------------------------------------------------------------------
# In a real project this calls Groq / Anthropic / a local model.
# Here we simulate it with a sleep so you can FEEL the speed difference.
def call_llm(prompt: str, model: str, temperature: float) -> str:
    """Pretend to call an LLM. This is the slow + expensive part."""
    print(f"   [LLM] Real API call (slow, costs money)  model={model}")
    time.sleep(2)  # simulate 2 seconds of network + inference latency
    return f"Answer to: '{prompt}' (generated by {model})"


# ---------------------------------------------------------------------------
# 4. THE CACHE-AWARE WRAPPER  (this is the whole point)
# ---------------------------------------------------------------------------
def ask_llm(prompt: str,
            model: str = "llama-3.3-70b-versatile",
            temperature: float = 0.0,
            ttl_seconds: int = 3600) -> str:
    """
    Ask the LLM, but check Redis first.

    ttl_seconds : how long the answer stays cached (Time-To-Live).
                  3600 = 1 hour. After that Redis auto-deletes it, so if the
                  underlying knowledge changes, users eventually get fresh
                  answers. This is your defense against stale data.
    """
    key = make_llm_cache_key(prompt, model, temperature)

    # --- STEP A: try the cache first (CACHE READ) ---
    cached = r.get(key)
    if cached is not None:
        print("   [CACHE HIT]  Served from Redis in ~0ms, $0 cost")
        return cached

    # --- STEP B: cache miss -> do the expensive work ---
    print("   [CACHE MISS] Nothing in Redis, must call the LLM")
    answer = call_llm(prompt, model, temperature)

    # --- STEP C: store the result for next time (CACHE WRITE) ---
    # SET key value EX ttl   ->  store with automatic expiration.
    r.set(key, answer, ex=ttl_seconds)
    return answer


# ---------------------------------------------------------------------------
# 5. DEMO  ->  run:  python 01_llm_cache.py
# ---------------------------------------------------------------------------
if __name__ == "__main__":
    question = "What is your refund policy?"
    other_question = "How do I reset my password?"
    model = "llama-3.3-70b-versatile"
    temperature = 0.0

    # Keep the demo output predictable even if you ran it before.
    r.delete(
        make_llm_cache_key(question, model, temperature),
        make_llm_cache_key(other_question, model, temperature),
    )

    print("\n--- 1st call (expect a MISS, will be slow) ---")
    t0 = time.time()
    print("RESULT:", ask_llm(question, model=model, temperature=temperature))
    print(f"Took {time.time() - t0:.2f}s\n")

    print("--- 2nd call, SAME question (expect a HIT, will be instant) ---")
    t0 = time.time()
    print("RESULT:", ask_llm(question, model=model, temperature=temperature))
    print(f"Took {time.time() - t0:.2f}s\n")

    print("--- 3rd call, DIFFERENT question (expect a MISS again) ---")
    t0 = time.time()
    print("RESULT:", ask_llm(other_question, model=model, temperature=temperature))
    print(f"Took {time.time() - t0:.2f}s\n")

    # TAKEAWAY:
    # 1st call ~2s (LLM). 2nd call ~0s (Redis). Same answer, huge savings.
    # In production this cuts both your latency AND your API bill dramatically.
